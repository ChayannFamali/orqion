/**
 * Оценка токенов для индикатора занятости контекста (T-442).
 *
 * Клиентская эвристика: ~3 символа на токен — компромисс между английским
 * (~4 символа/токен у cl100k) и кириллицей (~2 символа/токен). Точный
 * подсчёт (tiktoken) живёт на бэкенде; индикатор — ориентир, не биллинг.
 */
export function estimateTokens(text: string): number {
  if (!text) return 0;
  return Math.ceil(text.length / 3);
}
